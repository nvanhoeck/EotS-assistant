// Writes src/helper/rulePages.ts (section id -> [first page, last page]) from the ingested rulebook.
import { readFileSync, writeFileSync } from 'node:fs';

const raw = JSON.parse(readFileSync(new URL('../../server/data/chunks.json', import.meta.url), 'utf8'));
const chunks = Array.isArray(raw) ? raw : raw.chunks;

const pages = new Map();
for (const c of chunks) {
  const cur = pages.get(c.sectionId);
  pages.set(c.sectionId, [Math.min(cur?.[0] ?? c.pageStart, c.pageStart), Math.max(cur?.[1] ?? c.pageEnd, c.pageEnd)]);
}

const natural = (a, b) => {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] ?? -1) - (pb[i] ?? -1);
    if (d !== 0) return d;
  }
  return 0;
};

const lines = [...pages.keys()].sort(natural).map((id) => `  '${id}': [${pages.get(id).join(', ')}],`);
const body =
  '// Generated by scripts/gen-rule-pages.mjs from server/data/chunks.json. Do not edit by hand.\n' +
  'export const RULE_PAGES: Record<string, [number, number]> = {\n' +
  lines.join('\n') +
  '\n};\n';
writeFileSync(new URL('../src/helper/rulePages.ts', import.meta.url), body);
console.log(`Wrote ${lines.length} sections.`);
